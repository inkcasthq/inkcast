"""Generate the PrometheusRule component from the alert catalogue and the SLOs (libs/alerting.py).

    scripts/gen-alerts.py          # rewrite the files
    scripts/gen-alerts.py --check  # exit 1 if they are out of date (CI and tests run this)

Writes deploy/kustomize/components/prometheus-rules/{kustomization.yaml,prometheusrule.yaml}. Add the
component to an overlay that has the Prometheus Operator (the `servicemonitor` component's neighbour).
Also writes deploy/dev/prometheus/rules.yaml: the same groups as a plain rules file, for the local Prometheus
in deploy/dev (Docker Compose and kind), which runs without the Operator.
"""

from __future__ import annotations

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from inkcast.libs.alerting import prometheus_rule  # noqa: E402

OUT = ROOT / "deploy" / "kustomize" / "components" / "prometheus-rules"
DEV_RULES = ROOT / "deploy" / "dev" / "prometheus" / "rules.yaml"
HEADER = "# GENERATED by scripts/gen-alerts.py from libs/alerting.py (the alert catalogue and SLOs). Do not edit.\n"


def files() -> dict[pathlib.Path, str]:
    kustomization = {"apiVersion": "kustomize.config.k8s.io/v1alpha1", "kind": "Component",
                     "resources": ["prometheusrule.yaml"]}
    return {
        OUT / "kustomization.yaml": HEADER + yaml.safe_dump(kustomization, sort_keys=False),
        OUT / "prometheusrule.yaml": HEADER + yaml.safe_dump(prometheus_rule(), sort_keys=False, width=120),
        DEV_RULES: HEADER + yaml.safe_dump(prometheus_rule()["spec"], sort_keys=False, width=120),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, text in files().items():
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Out of date (run scripts/gen-alerts.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
