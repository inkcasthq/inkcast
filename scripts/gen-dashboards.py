"""Generate the operator Grafana dashboard (libs/dashboards.py) and its sidecar ConfigMap component.

    scripts/gen-dashboards.py          # rewrite the files
    scripts/gen-dashboards.py --check  # exit 1 if they are out of date (tests run this)

Writes deploy/kustomize/components/dashboards/{kustomization.yaml,grafana-inkcast-platform.json}. The Perses
form for the OpenShift console is produced from the JSON with the diagram-kit `perses-dashboard` command.
"""

from __future__ import annotations

import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from inkcast.libs.dashboards import platform_dashboard  # noqa: E402

OUT = ROOT / "deploy" / "kustomize" / "components" / "dashboards"
HEADER = "# GENERATED by scripts/gen-dashboards.py from libs/dashboards.py. Do not edit.\n"


def files() -> dict[pathlib.Path, str]:
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1", "kind": "Component",
        "configMapGenerator": [{"name": "inkcast-grafana-dashboards", "options": {
            "disableNameSuffixHash": True, "labels": {"grafana_dashboard": "1"}},
            "files": ["grafana-inkcast-platform.json"]}],
    }
    return {
        OUT / "kustomization.yaml": HEADER + yaml.safe_dump(kustomization, sort_keys=False),
        OUT / "grafana-inkcast-platform.json": json.dumps(platform_dashboard(), indent=2) + "\n",
        # The local stack (deploy/dev, Compose and kind) loads the same JSON from inside its own kustomization root.
        ROOT / "deploy" / "dev" / "grafana" / "dashboards" / "grafana-inkcast-platform.json":
            json.dumps(platform_dashboard(), indent=2) + "\n",
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, text in files().items():
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Out of date (run scripts/gen-dashboards.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
