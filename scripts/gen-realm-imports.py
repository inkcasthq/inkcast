"""Generate the lab's Keycloak realms as code: one KeycloakRealmImport per environment, from the one realm file.

    scripts/gen-realm-imports.py          # rewrite the files
    scripts/gen-realm-imports.py --check  # exit 1 if they are out of date (tests run this)

Writes deploy/kustomize/shared/keycloak-realms/realm-inkcast-<side>.yaml for staging and prod (issue #305, D1): the
realm of deploy/keycloak/realm-inkcast.json, unchanged but for its name (inkcast-<side>), the environment's public URL
in place of ${INKCAST_PUBLIC_URL} (the client's redirect, read from environments/<env>/kustomization.yaml, so the
redirect and the Route host move together), and SMTP pointing at the Mailpit of the same kustomization. The two
client secrets stay ${...} placeholders, declared under spec.placeholders from Secret inkcast-<side>-realm in the
keycloak namespace, the one env-secrets writes (#323); no secret value is ever rendered.

The contract is the operator's at Keycloak 26.6.7 (operator/src/main/java/org/keycloak/operator at that tag):
k8s.keycloak.org/v2beta1 (Constants.CRDS_VERSION; v2alpha1 is still served, deprecated), spec.keycloakCRName and
spec.realm required (KeycloakRealmImportSpec), spec.placeholders a map of environment-variable name to
{secret: {name, key}} (Placeholder: Secrets only, in the Keycloak CR's namespace), each becoming an environment
variable of the import Job from that Secret key (KeycloakRealmImportJobDependentResource), which `kc.sh import`
resolves in the realm text (Import.java turns replacement on; an unresolved ${X} stays literal, so this script
refuses a placeholder the contract does not feed). The import runs `--override=false`: a realm that already exists
is skipped, never changed (ImportUtils "Import skipped"; the operator guide: "The Realm Import CR only supports
creation of new realms").
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
REALM = pathlib.Path("deploy/keycloak/realm-inkcast.json")
ENVIRONMENTS = pathlib.Path("deploy/kustomize/environments")
OUT = pathlib.Path("deploy/kustomize/shared/keycloak-realms")
SIDES = {"staging": "staging", "production": "prod"}     # environment directory: the suffix of every name
NAMESPACE = "keycloak"                                   # the lab's Keycloak: its CR, its pods, the realm Secrets
KEYCLOAK_CR = "keycloak"
KEYCLOAK_ISSUER = "https://keycloak.apps-crc.testing/realms/"   # what each environment's OIDC_ISSUER must start with
# The realm file's secret placeholders, each fed from this key of Secret inkcast-<side>-realm (#323's contract).
PLACEHOLDERS = {"KC_INKCAST_CLIENT_SECRET": "identity-client-secret", "KC_INKCAST_SYNC_SECRET": "sync-client-secret"}
# A variable name as kc.sh import resolves it from the import Job's environment: ${X}, ${X:default} or ${X,Y}
# (StringPropertyReplacer). Keycloak's own message keys (${client_account}) name no variable and stay as they are.
PLACEHOLDER = re.compile(r"\$\{([A-Z0-9_]+)(?=[}:,])")
LABELS = {"app.kubernetes.io/name": "keycloak-realm", "app.kubernetes.io/part-of": "inkcast",
          "app.kubernetes.io/component": "identity"}
HEADER = ("# GENERATED by scripts/gen-realm-imports.py from deploy/keycloak/realm-inkcast.json and the environment's\n"
          "# kustomization. Do not edit: change the realm file or the environment, then run the script (#305).\n")


def literals(root: pathlib.Path, env: str) -> dict[str, str]:
    """The environment's inkcast-config literals: INKCAST_PUBLIC_URL, OIDC_ISSUER, OIDC_CLIENT_ID (#314)."""
    kustomization = yaml.safe_load((root / ENVIRONMENTS / env / "kustomization.yaml").read_text())
    generator = next(g for g in kustomization["configMapGenerator"] if g["name"] == "inkcast-config")
    return dict(lit.split("=", 1) for lit in generator["literals"])


def mailpit(root: pathlib.Path) -> tuple[str, str]:
    """Mailpit's SMTP host and port, from its Service in the same kustomization: the realm's mail goes there."""
    docs = [d for d in yaml.safe_load_all((root / OUT / "mailpit.yaml").read_text()) if d]
    (service,) = [d for d in docs if d["kind"] == "Service" and d["metadata"]["name"] == "mailpit"]
    port = next(p["port"] for p in service["spec"]["ports"] if p["name"] == "smtp")
    return f"{service['metadata']['name']}.{NAMESPACE}.svc", str(port)


def realm_import(root: pathlib.Path, env: str, side: str) -> dict:
    name = f"inkcast-{side}"
    settings = literals(root, env)
    public_url = settings["INKCAST_PUBLIC_URL"].rstrip("/")     # as libs/config.py reads it: the redirect login.py sends
    if settings.get("OIDC_ISSUER") != f"{KEYCLOAK_ISSUER}{name}":
        raise SystemExit(f"{env}: OIDC_ISSUER must be {KEYCLOAK_ISSUER}{name} (the realm imported for it), "
                         f"not {settings.get('OIDC_ISSUER')!r}")
    text = (root / REALM).read_text().replace("${INKCAST_PUBLIC_URL}", public_url)
    realm = json.loads(text)
    realm["realm"] = name
    if settings.get("OIDC_CLIENT_ID") not in [c["clientId"] for c in realm["clients"]]:
        raise SystemExit(f"{env}: OIDC_CLIENT_ID {settings.get('OIDC_CLIENT_ID')!r} is not a client of the realm file")
    host, port = mailpit(root)
    # Plain SMTP to the mail catcher, no auth: the file's user and password placeholders have nothing to carry.
    realm["smtpServer"] = {"host": host, "port": port, "from": f"no-reply@{public_url.removeprefix('https://')}",
                           "fromDisplayName": realm["smtpServer"]["fromDisplayName"],
                           "auth": "false", "starttls": "false", "ssl": "false"}
    # The import Job copies the Keycloak server's pod, so its environment holds the server's own secrets (the database
    # password among them) beside the placeholders: the only variable the realm may name is a client's secret, fed.
    fed = {f"${{{var}}}" for var in PLACEHOLDERS}
    rest = [{k: v for k, v in c.items() if not (k == "secret" and v in fed)} for c in realm["clients"]]
    stray = set(PLACEHOLDER.findall(json.dumps({**realm, "clients": rest})))
    if stray:
        raise SystemExit(f"{env}: the realm file uses {sorted(stray)} outside a client's secret fed by inkcast-{side}-realm; "
                         "Keycloak would fill it from the import Job's environment or leave it literal")
    placeholders = {var: {"secret": {"name": f"inkcast-{side}-realm", "key": key}} for var, key in PLACEHOLDERS.items()}
    return {
        "apiVersion": "k8s.keycloak.org/v2beta1", "kind": "KeycloakRealmImport",
        "metadata": {"name": name, "namespace": NAMESPACE, "labels": {**LABELS, "inkcast.io/environment": side}},
        "spec": {"keycloakCRName": KEYCLOAK_CR, "placeholders": placeholders, "realm": realm},
    }


def files(root: pathlib.Path = ROOT) -> dict[pathlib.Path, str]:
    return {root / OUT / f"realm-inkcast-{side}.yaml": HEADER + yaml.safe_dump(realm_import(root, env, side),
                                                                                sort_keys=False, width=120)
            for env, side in SIDES.items()}


def main(argv: list[str], root: pathlib.Path = ROOT) -> int:
    stale = []
    for path, text in files(root).items():
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Out of date (run scripts/gen-realm-imports.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
