"""Generate the split-service Kustomize components from the service registry and route table.

    scripts/gen-manifests.py          # rewrite the files
    scripts/gen-manifests.py --check  # exit 1 if they are out of date (CI and tests run this)

Writes:
  deploy/kustomize/components/split-services/   one Deployment + Service per service, the built-in
                                                Gateway in front (behind the existing `inkcast` Service)
  deploy/kustomize/components/gateway-api/      HTTPRoutes per public path, straight to each service,
                                                for clusters with a Gateway API implementation
"""

from __future__ import annotations

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from inkcast.launcher import BUILTIN  # noqa: E402
from inkcast.libs.contracts.routes import ROUTES  # noqa: E402
from inkcast.libs.config import SHUTDOWN_GRACE_CEILING  # noqa: E402

COMPONENTS = ROOT / "deploy" / "kustomize" / "components"
HEADER = "# GENERATED by scripts/gen-manifests.py from the service registry and route table. Do not edit.\n"
LABELS = {"app.kubernetes.io/name": "inkcast", "app.kubernetes.io/part-of": "inkcast"}
SERVICES = ["IdentityService", "PublishingApi", "ConnectorService", "SchedulerWorker", "InsightsService", "Gateway"]
DATA_OWNER = "publishing-api"  # until PostgreSQL (E3) every pod that uses SQLite runs on this pod's node


def dump(docs: list[dict]) -> str:
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False, width=120) for d in docs)


def deployment(app: str) -> dict:
    spec = BUILTIN[app]
    full = spec.full_name
    sel = {"app.kubernetes.io/component": "server", "inkcast.io/service": full}
    is_gateway = app == "Gateway"
    env = [{"name": "INKCAST_APP_NAME", "value": app}]
    if is_gateway:
        env += [{"name": f"INKCAST_UPSTREAM_{BUILTIN[s].full_name.upper().replace('-', '_')}",
                 "value": f"http://inkcast-{BUILTIN[s].full_name}:8787"} for s in ROUTES]
    else:
        env += [{"name": "INKCAST_SECRET_KEY_FILE", "value": "/var/run/secrets/inkcast/secret-key"}]
        if "login" in spec.needs:
            env += [{"name": "OIDC_CLIENT_SECRET_FILE", "value": "/var/run/secrets/inkcast/oidc-client-secret"}]
    ports = [{"name": "metrics", "containerPort": 9090}]
    if spec.kind == "http":
        ports.insert(0, {"name": "http", "containerPort": 8787})
    mounts = [{"name": "tmp", "mountPath": "/tmp"}]
    volumes = [{"name": "tmp", "emptyDir": {"sizeLimit": "64Mi"}}]
    if not is_gateway:
        mounts += [{"name": "data", "mountPath": "/data"},
                   {"name": "secrets", "mountPath": "/var/run/secrets/inkcast", "readOnly": True}]
        volumes += [{"name": "data", "persistentVolumeClaim": {"claimName": "inkcast-data"}},
                    {"name": "secrets", "secret": {"secretName": "inkcast-secrets", "defaultMode": 0o440}}]
    pod: dict = {
        "serviceAccountName": "inkcast",
        "automountServiceAccountToken": False,
        "enableServiceLinks": False,
        "terminationGracePeriodSeconds": SHUTDOWN_GRACE_CEILING,   # INKCAST_SHUTDOWN_GRACE stays under it
        "securityContext": {"runAsNonRoot": True, "seccompProfile": {"type": "RuntimeDefault"}},
        "containers": [{
            "name": "inkcast",
            "image": "inkcast",
            "args": ["run", app],
            "ports": ports,
            "envFrom": [{"configMapRef": {"name": "inkcast-config"}}],
            "env": env,
            "startupProbe": {"httpGet": {"path": "/livez", "port": "metrics"}, "periodSeconds": 2, "failureThreshold": 30},
            "livenessProbe": {"httpGet": {"path": "/livez", "port": "metrics"}, "periodSeconds": 10, "failureThreshold": 3},
            "readinessProbe": {"httpGet": {"path": "/readyz", "port": "metrics"}, "periodSeconds": 10, "failureThreshold": 3},
            "resources": {"requests": {"cpu": "25m", "memory": "96Mi"}, "limits": {"memory": "256Mi"}},
            "securityContext": {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True,
                                "capabilities": {"drop": ["ALL"]}},
            "volumeMounts": mounts,
        }],
        "volumes": volumes,
    }
    if not is_gateway and full != DATA_OWNER:
        pod["affinity"] = {"podAffinity": {"requiredDuringSchedulingIgnoredDuringExecution": [{
            "labelSelector": {"matchLabels": {"inkcast.io/service": DATA_OWNER}},
            "topologyKey": "kubernetes.io/hostname"}]}}
    return {
        "apiVersion": "apps/v1", "kind": "Deployment",
        "metadata": {"name": f"inkcast-{full}", "labels": {**LABELS, **sel}},
        "spec": {
            "replicas": 1,
            # SQLite: one writer per service, never two pods of a service at once. Gateway is stateless.
            "strategy": {"type": "RollingUpdate"} if is_gateway else {"type": "Recreate"},
            "revisionHistoryLimit": 3,
            "selector": {"matchLabels": {**LABELS, **sel}},
            "template": {"metadata": {"labels": {**LABELS, **sel}}, "spec": pod},
        },
    }


def service(app: str) -> dict:
    full = BUILTIN[app].full_name
    return {"apiVersion": "v1", "kind": "Service",
            "metadata": {"name": f"inkcast-{full}", "labels": {**LABELS, "inkcast.io/service": full}},
            "spec": {"selector": {**LABELS, "inkcast.io/service": full},
                     "ports": [{"name": "http", "port": 8787, "targetPort": "http"}]}}


def internal_policy() -> dict:
    """The gateway may call the services (port 8787); nothing else inside the namespace may."""
    return {
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
        "metadata": {"name": "inkcast-internal", "labels": LABELS},
        "spec": {
            "podSelector": {"matchLabels": {"app.kubernetes.io/component": "server"}},
            "policyTypes": ["Ingress", "Egress"],
            "ingress": [{"from": [{"podSelector": {"matchLabels": {"inkcast.io/service": "gateway"}}}],
                         "ports": [{"port": 8787, "protocol": "TCP"}]}],
            "egress": [{"to": [{"podSelector": {"matchLabels": {"app.kubernetes.io/component": "server"}}}],
                        "ports": [{"port": 8787, "protocol": "TCP"}]}],
        },
    }


def split_kustomization() -> dict:
    return {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1", "kind": "Component",
        "resources": ["deployments.yaml", "services.yaml", "networkpolicy.yaml"],
        "patches": [
            # The single all-in-one Deployment gives way to one Deployment per service.
            {"target": {"kind": "Deployment", "name": "inkcast"},
             "patch": "$patch: delete\napiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: inkcast\n"},
            # The public `inkcast` Service (behind the Route / HTTPRoute) now fronts the built-in Gateway.
            {"target": {"kind": "Service", "name": "inkcast"},
             "patch": "- op: add\n  path: /spec/selector/inkcast.io~1service\n  value: gateway\n"},
        ],
        "images": [{"name": "inkcast", "newName": "ghcr.io/inkcasthq/inkcast", "newTag": "0.1.0"}],
    }


def httproutes() -> list[dict]:
    docs = []
    for app, paths in ROUTES.items():
        full = BUILTIN[app].full_name
        docs.append({
            "apiVersion": "gateway.networking.k8s.io/v1", "kind": "HTTPRoute",
            "metadata": {"name": f"inkcast-{full}", "labels": LABELS},
            "spec": {
                "parentRefs": [{"name": "public", "namespace": "gateway-system", "sectionName": "https"}],
                "hostnames": ["inkcast.example.com"],
                "rules": [{"matches": [{"path": {"type": "PathPrefix", "value": p.rstrip("/") or "/"}} for p in paths],
                           "backendRefs": [{"name": f"inkcast-{full}", "port": 8787}]}],
            },
        })
    return docs


def gateway_api_kustomization() -> dict:
    return {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1", "kind": "Component",
        "resources": ["httproutes.yaml"],
        "patches": [
            # The cluster's Gateway routes by path now; the single catch-all HTTPRoute and the built-in
            # Gateway are no longer needed. Use after the split-services component.
            {"target": {"kind": "HTTPRoute", "name": "inkcast"},
             "patch": "$patch: delete\napiVersion: gateway.networking.k8s.io/v1\nkind: HTTPRoute\nmetadata:\n  name: inkcast\n"},
            {"target": {"kind": "Deployment", "name": "inkcast-gateway"},
             "patch": "$patch: delete\napiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: inkcast-gateway\n"},
        ],
    }


def files() -> dict[pathlib.Path, str]:
    split, gapi = COMPONENTS / "split-services", COMPONENTS / "gateway-api"
    return {
        split / "kustomization.yaml": dump([split_kustomization()]),
        split / "deployments.yaml": dump([deployment(a) for a in SERVICES]),
        split / "services.yaml": dump([service(a) for a in SERVICES if BUILTIN[a].kind == "http" and a != "Gateway"]),
        split / "networkpolicy.yaml": dump([internal_policy()]),
        gapi / "kustomization.yaml": dump([gateway_api_kustomization()]),
        gapi / "httproutes.yaml": dump(httproutes()),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, text in files().items():
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Out of date (run scripts/gen-manifests.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
